/**
 * Перевод ошибок Broma16 на человеческий язык.
 *
 * Их 422 приходит в виде «поле: правило» — например `title: does not match`
 * или `file: rule: image_dimensions`. Оператору такое ничего не говорит: он
 * видит красную надпись и не понимает, что чинить. Здесь эти правила
 * превращаются в подсказку с конкретным действием.
 *
 * Исходный текст не выбрасываем — он нужен в логах и при переписке с
 * поддержкой Broma16, поэтому подсказка идёт первой, а оригинал в скобках.
 */

type Hint = { match: RegExp; hint: string };

/**
 * Порядок важен: первое совпадение выигрывает, поэтому частные правила должны
 * стоять выше общих.
 */
const HINTS: Hint[] = [
  {
    match: /title.*(does not match|not match)/i,
    hint:
      "Название релиза и название трека должны совпадать. Для сингла Broma16 требует их полного совпадения — " +
      "проверьте оба поля, включая раскладку: латинская «c» и кириллическая «с» выглядят одинаково, но это разные символы.",
  },
  {
    match: /image_dimensions|cover.*dimension/i,
    hint:
      "Обложка не проходит по размеру. Нужен квадрат не меньше 3000×3000 пикселей, JPG или PNG. " +
      "Загрузите файл заново на странице релиза.",
  },
  {
    match: /image_format|file.*format|mime/i,
    hint: "Формат файла не подходит. Обложка — JPG или PNG, аудио — WAV или FLAC.",
  },
  {
    match: /isrc/i,
    hint:
      "Проблема с ISRC. Код должен быть из 12 символов вида TJA012600001 и не повторяться у разных записей. " +
      "При переносе каталога указывайте оригинальный код, а не новый.",
  },
  {
    match: /ean|upc|barcode/i,
    hint: "Проблема со штрихкодом (UPC/EAN). Он должен быть уникальным — возможно, такой релиз в Broma16 уже есть.",
  },
  {
    match: /producer|party_id/i,
    hint: "Не указан продюсер записи. Добавьте его в разделе «Производство» у трека — без этого Broma16 не примет релиз.",
  },
  {
    match: /contributor|author|ownership/i,
    hint: "Проблема с авторами произведения. Проверьте, что авторы указаны и их доли в сумме дают ровно 100%.",
  },
  {
    // Отдельно от общего правила про даты: у старта продаж своё требование —
    // не раньше чем через неделю. Прежняя подсказка говорила «не раньше
    // сегодняшней», из-за чего дату ставили на завтра и получали тот же отказ.
    match: /sale_start_date/i,
    hint: "Дата старта продаж слишком близкая. Broma16 принимает её не раньше чем через 7 дней от сегодняшнего числа. " +
      "Если релиз уже выходил у другого дистрибьютора — включите «Перенос каталога», для переносов это ограничение не действует.",
  },
  {
    match: /created_date|release_date|date/i,
    hint: "Проблема с датой. Дата релиза должна быть заполнена, а для первой отправки — не раньше чем через 7 дней.",
  },
  {
    match: /genre/i,
    hint: "Жанр не распознан Broma16. Выберите значение из справочника, а не вписывайте своё.",
  },
  {
    match: /language/i,
    hint: "Язык не распознан. Выберите его из списка на странице релиза.",
  },
  {
    match: /audio|duration|sample|bitrate/i,
    hint: "Проблема с аудиофайлом. Нужен WAV или FLAC, 16 или 24 бит, частота от 44.1 кГц.",
  },
];

/**
 * Добавляет к ошибке Broma16 понятное объяснение. Если правило незнакомо,
 * возвращает исходный текст без изменений — выдумывать объяснение хуже, чем
 * показать как есть.
 */
export function explainBroma16Error(raw: string | null | undefined): string {
  const text = (raw ?? "").trim();
  if (!text) return "";
  const found = HINTS.find((h) => h.match.test(text));
  return found ? `${found.hint} (ответ Broma16: ${text})` : text;
}
